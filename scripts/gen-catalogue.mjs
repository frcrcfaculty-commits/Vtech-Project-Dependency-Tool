// Generates supabase/seed/catalogue.sql from products.csv + product_steps.csv
// (extracted from sheet "Ashutosh Project Status" → tab "Hansal"). Usage: node scripts/gen-catalogue.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const dir = join(dirname(fileURLToPath(import.meta.url)), '../supabase/seed');
const parse = (text) => {
  const rows = []; let row = [], f = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"' && text[i + 1] === '"') { f += '"'; i++; } else if (c === '"') q = false; else f += c; }
    else if (c === '"') q = true; else if (c === ',') { row.push(f); f = ''; }
    else if (c === '\n') { row.push(f); rows.push(row); row = []; f = ''; } else if (c !== '\r') f += c;
  }
  if (f || row.length) { row.push(f); rows.push(row); }
  const [h, ...rest] = rows.filter((r) => r.length > 1);
  return rest.map((r) => Object.fromEntries(h.map((k, i) => [k, r[i]])));
};
const sq = (s) => `'${String(s).replace(/'/g, "''")}'`;
const products = parse(readFileSync(join(dir, 'products.csv'), 'utf8'));
const steps = parse(readFileSync(join(dir, 'product_steps.csv'), 'utf8'));

let out = '-- GENERATED by scripts/gen-catalogue.mjs — do not edit by hand. Idempotent.\n\n' +
  "update public.agency_types set internal = true where name in ('VTech', 'VTech Installers', 'VTech Programmers', 'VTech Project Managers');\n\n";
out += 'insert into public.product_catalogue (title, scope, location_options, sort) values\n' +
  products.map((p) => `  (${sq(p.title)}, ${sq(p.scope)}, ${p.location_options ? `array[${p.location_options.split('|').map(sq).join(', ')}]` : `'{}'::text[]`}, ${Number(p.sort)})`).join(',\n') +
  '\non conflict (lower(title)) do nothing;\n\n';
out += 'insert into public.product_steps (product_id, seq, label, phase, responsibility, gate, default_agency_type_id, sheet_colour)\n' +
  'select p.id, v.seq, v.label, v.phase, v.resp, v.gate, t.id, v.colour\nfrom (values\n' +
  steps.map((s) => `  (${sq(s.product)}, ${Number(s.seq)}, ${sq(s.label)}, ${Number(s.phase)}, ${sq(s.responsibility)}, ${sq(s.gate)}, ${sq(s.default_agency_type)}, ${sq(s.sheet_colour)})`).join(',\n') +
  '\n) as v(product, seq, label, phase, resp, gate, type_name, colour)\n' +
  'join public.product_catalogue p on lower(p.title) = lower(v.product)\njoin public.agency_types t on lower(t.name) = lower(v.type_name)\n' +
  'on conflict (product_id, seq) do nothing;\n';
writeFileSync(join(dir, 'catalogue.sql'), out);
console.log(`catalogue.sql: ${products.length} products, ${steps.length} steps`);
