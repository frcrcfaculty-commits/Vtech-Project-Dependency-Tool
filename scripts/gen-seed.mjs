// Generates supabase/seed/seed.sql from master_dependencies.csv + presets.
// Usage: node scripts/gen-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const csv = readFileSync(join(root, 'supabase/seed/master_dependencies.csv'), 'utf8');

function parseCsv(text) {
  const rows = [];
  let row = [], field = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') q = false;
      else field += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c !== '\r') field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const [header, ...rows] = parseCsv(csv).filter((r) => r.length > 1);
const idx = Object.fromEntries(header.map((h, i) => [h, i]));
const sq = (s) => `'${String(s).replace(/'/g, "''")}'`;

const typeOrder = [];
for (const r of rows) if (!typeOrder.includes(r[idx.agency_type])) typeOrder.push(r[idx.agency_type]);

const roomPresets = [
  'Living Room', 'Dining Room', 'Kitchen', 'Family Lounge', 'Foyer / Entrance Lobby', 'Main Entrance',
  'Exit Area', 'Lift Lobby', 'Corridor / Passage', 'Staircase', 'Powder Room',
  'Master Bedroom', 'Master Bathroom', 'Master Walk-in', 'His Walk-in', 'Her Walk-in',
  "Parents' Bedroom", "Parents' Bathroom", "Parents' Walk-in",
  "Son's Bedroom", "Son's Bathroom", "Daughter's Bedroom", "Daughter's Bathroom", "Kids' Room",
  'Guest Bedroom', 'Guest Bathroom', 'Home Theatre', 'Entertainment Area', 'Home Office / Study',
  'Mandir / Pooja Room', 'Bar Area', 'Gym', 'Spa / Steam', 'Pool Area', 'Balcony / Deck', 'Terrace',
  'Servant Room', 'Utility / Laundry', 'DB / Rack Room', 'Garage / Parking'
];

const defaultTerms =
  'General terms and attention\n' +
  '1. Once the dependency is addressed, VTech requires a minimum of 2 to 4 days to complete the automation work of installing, integrating and programming the devices.\n' +
  '2. Automation products are usually installed after all agencies complete their work. Due to client insistence we are proceeding with the installation. The installed products are very expensive; we request the respective agencies to take adequate measures to cover/protect the automation devices to avoid any loss to the client.';

let out = '-- GENERATED by scripts/gen-seed.mjs — do not edit by hand.\n\n';
out += 'insert into public.agency_types (name, sort) values\n' +
  typeOrder.map((t, i) => `  (${sq(t)}, ${i + 1})`).join(',\n') + '\non conflict do nothing;\n\n';

out += 'insert into public.master_dependencies (agency_type_id, seq, text, active, origin, source_note)\nselect t.id, v.seq, v.text, v.active, v.origin, v.note\nfrom (values\n' +
  rows.map((r) => `  (${sq(r[idx.agency_type])}, ${Number(r[idx.seq])}, ${sq(r[idx.text])}, ${r[idx.active] === 'true'}, ${sq(r[idx.origin])}, ${sq(r[idx.original_text])})`).join(',\n') +
  '\n) as v(type_name, seq, text, active, origin, note)\njoin public.agency_types t on lower(t.name) = lower(v.type_name)\non conflict do nothing;\n\n';

out += `insert into public.app_settings (key, value) values\n  ('default_terms', to_jsonb(${sq(defaultTerms)}::text)),\n  ('room_presets', ${sq(JSON.stringify(roomPresets))}::jsonb)\non conflict (key) do nothing;\n`;

writeFileSync(join(root, 'supabase/seed/seed.sql'), out);
console.log(`seed.sql: ${typeOrder.length} agency types, ${rows.length} dependencies (${rows.filter((r) => r[idx.active] === 'true').length} active), ${roomPresets.length} room presets`);
